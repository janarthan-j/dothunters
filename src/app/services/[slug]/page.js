export function generateStaticParams() {
  return services.map((s) => ({ slug: s.slug }));
}

export function generateMetadata({ params }) {
  const service = getServiceBySlug(params.slug);
  if (!service) return {};
  // Share card generated by `npm run og` (scripts/generate-og-images.mjs)
  const image = { url: `/og/services/${service.slug}.png`, width: 1200, height: 630, alt: `${service.title} — DotHunters` };
  return {
    title: service.title,
    description: service.tagline,
    // A child openGraph replaces the parent's, so repeat the site-level fields
    openGraph: {
      type: "website",
      siteName: "DotHunters",
      locale: "en_US",
      title: `${service.title} | DotHunters`,
      description: service.description,
      url: `/services/${service.slug}`,
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: `${service.title} | DotHunters`,
      description: service.tagline,
      images: [image.url],
    },
  };
}

